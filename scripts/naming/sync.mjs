import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "../..");
const configPath = resolve(repoRoot, "config/naming.json");
const checkMode = process.argv.includes("--check");

const naming = JSON.parse(readFileSync(configPath, "utf8"));

function formatJson(value) {
  return JSON.stringify(value, null, 2);
}

function syncFile(filePath, nextContent) {
  let currentContent = "";
  try {
    currentContent = readFileSync(filePath, "utf8");
  } catch {
    currentContent = "";
  }

  if (currentContent === nextContent) {
    return;
  }

  const display = relative(repoRoot, filePath);
  if (checkMode) {
    console.error(`[naming:sync] drift detected: ${display}`);
    process.exitCode = 1;
    return;
  }

  writeFileSync(filePath, nextContent, "utf8");
  console.log(`[naming:sync] updated ${display}`);
}

const brandTs = `// Generated by scripts/naming/sync.mjs. Do not edit manually.\nexport const BRAND_NAME = ${JSON.stringify(naming.brand.name)};\nexport const BRAND_SLUG = ${JSON.stringify(naming.brand.slug)};\nexport const LEGACY_BRAND_SLUG = ${JSON.stringify(naming.brand.legacySlug)};\nexport const BRAND_BOT_USER_AGENT = ${JSON.stringify(naming.brand.botUserAgent)};\nexport const BRAND_SNAPSHOT_FALLBACK_URL = ${JSON.stringify(naming.brand.snapshotFallbackUrl)};\nexport const DEFAULT_DEMO_EMAIL = ${JSON.stringify(naming.brand.defaultDemoEmail)};\nexport const DEFAULT_ADMIN_EMAIL = ${JSON.stringify(naming.brand.defaultAdminEmail)};\n`;

const namingTs = `// Generated by scripts/naming/sync.mjs. Do not edit manually.\n\nexport const BRAND = ${formatJson(naming.brand)} as const;\n\nexport const PACKAGE_SCOPES = ${formatJson(naming.packages)} as const;\n\nexport const AUTH_COOKIE_NAMES = {\n  session: ${JSON.stringify(naming.auth.sessionCookie)},\n  oauthPrefix: ${JSON.stringify(naming.auth.oauthCookiePrefix)},\n  legacySession: ${JSON.stringify(naming.auth.legacySessionCookie)},\n  legacyOauthPrefix: ${JSON.stringify(naming.auth.legacyOauthCookiePrefix)}\n} as const;\n\nexport const EXTENSION_STORAGE_KEYS = ${formatJson(naming.extension.storageKeys)} as const;\n\nexport const LEGACY_EXTENSION_STORAGE_KEYS = ${formatJson(naming.extension.legacyStorageKeys)} as const;\n\nexport const RUNTIME_NAMING = ${formatJson(naming.runtime)} as const;\n\nexport const INFRA_NAMING = ${formatJson(naming.infra)} as const;\n`;

const runtimeNamingSh = `#!/usr/bin/env bash\n# Generated by scripts/naming/sync.mjs. Do not edit manually.\n\nRUNTIME_SERVICE_PREFIX="\${RUNTIME_SERVICE_PREFIX:-${naming.runtime.servicePrefix}}"\nRUNTIME_APP_USER="\${RUNTIME_APP_USER:-${naming.runtime.user}}"\nRUNTIME_APP_GROUP="\${RUNTIME_APP_GROUP:-${naming.runtime.group}}"\nRUNTIME_APP_DIR="\${RUNTIME_APP_DIR:-${naming.runtime.appDir}}"\nRUNTIME_STAGING_DIR="\${RUNTIME_STAGING_DIR:-${naming.runtime.stagingDir}}"\nRUNTIME_ETC_DIR="\${RUNTIME_ETC_DIR:-${naming.runtime.etcDir}}"\nRUNTIME_ENV_FILE="\${RUNTIME_ENV_FILE:-${naming.runtime.envFile}}"\n\nLEGACY_RUNTIME_SERVICE_PREFIX="${naming.runtime.legacy.servicePrefix}"\nLEGACY_RUNTIME_APP_USER="${naming.runtime.legacy.user}"\nLEGACY_RUNTIME_APP_GROUP="${naming.runtime.legacy.group}"\nLEGACY_RUNTIME_APP_DIR="${naming.runtime.legacy.appDir}"\nLEGACY_RUNTIME_STAGING_DIR="${naming.runtime.legacy.stagingDir}"\nLEGACY_RUNTIME_ETC_DIR="${naming.runtime.legacy.etcDir}"\nLEGACY_RUNTIME_ENV_FILE="${naming.runtime.legacy.envFile}"\n\nruntime_service_name() {\n  local unit="$1"\n  echo "\${RUNTIME_SERVICE_PREFIX}-\${unit}.service"\n}\n\nlegacy_runtime_service_name() {\n  local unit="$1"\n  echo "\${LEGACY_RUNTIME_SERVICE_PREFIX}-\${unit}.service"\n}\n`;

syncFile(resolve(repoRoot, "packages/core/src/config/brand.ts"), brandTs);
syncFile(resolve(repoRoot, "packages/core/src/config/naming.ts"), namingTs);
syncFile(resolve(repoRoot, "scripts/azure/runtime-naming.sh"), runtimeNamingSh);

if (process.exitCode && process.exitCode !== 0) {
  process.exit(process.exitCode);
}
