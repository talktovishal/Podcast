let bundledSilentMp3Buffer: Buffer | null = null;

export function resolveDemoAudioStrategy(input?: {
  ci?: string;
  platform?: NodeJS.Platform;
  runtimeProfile?: string;
}): DemoAudioStrategy {
  const runtimeProfile = input?.runtimeProfile ?? process.env.RUNTIME_PROFILE ?? "";
  const ci = input?.ci ?? process.env.CI ?? "";
  const platform = input?.platform ?? process.platform;

  if (runtimeProfile === "parity" || ci === "true") {
    return "fast";
  }

  if (platform === "darwin") {
    return "native";
  }

  return "provider";
}

export function getBundledDemoAudioBuffer(): Buffer {
  if (!bundledSilentMp3Buffer) {
    bundledSilentMp3Buffer = Buffer.from(BUNDLED_SILENT_MP3_BASE64, "base64");
  }

  // Return a copy so callers can safely treat the result as mutable.
  return Buffer.from(bundledSilentMp3Buffer);
}
