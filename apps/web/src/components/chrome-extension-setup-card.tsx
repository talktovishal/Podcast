"use client";

import Link from "next/link";
import { useEffect, useRef, useState } from "react";
import { CopyableValueBox } from "@/components/copyable-value-box";
import { copyText } from "@/lib/copy-text";

export const CHROME_WEB_STORE_URL =
  "https://chromewebstore.google.com/detail/articlepod-capture/epjncnckcohefbopcbpfppfgljkkcmgp";

type ExtensionConnectCodeResponse =
  | {
      ok: true;
      connectCode: string;
      expiresAt: string;
    }
  | {
      ok: false;
      errorMessage: string;
    };

async function requestExtensionConnectCode(): Promise<ExtensionConnectCodeResponse> {
  const response = await fetch("/api/auth/extension/connect-code", {
    method: "POST",
    headers: {
      "content-type": "application/json",
    },
    body: JSON.stringify({ label: "chrome-extension" }),
  });
  const json = (await response.json().catch(() => null)) as
    | {
        connect_code?: string;
        expires_at?: string;
        error_message?: string;
      }
    | null;

  if (!response.ok || !json?.connect_code || !json?.expires_at) {
    return {
      ok: false,
      errorMessage: json?.error_message || "Could not generate extension connect code.",
    };
  }

  return {
    ok: true,
    connectCode: json.connect_code,
    expiresAt: json.expires_at,
  };
}

type ChromeExtensionSetupCardProps = {
  isAuthenticated: boolean;
  id?: string;
  loginHref?: string;
};

export function ChromeExtensionSetupCard({
  isAuthenticated,
  id,
  loginHref = "/login",
}: ChromeExtensionSetupCardProps) {
  const [isBusy, setIsBusy] = useState(false);
  const [statusMessage, setStatusMessage] = useState<string | null>(null);
  const [extensionConnectCode, setExtensionConnectCode] = useState<string | null>(null);
  const [extensionCodeExpiresAt, setExtensionCodeExpiresAt] = useState<string | null>(null);
  const autoGeneratedRef = useRef(false);
  const connectCodeRequestRef = useRef<Promise<ExtensionConnectCodeResponse> | null>(null);

  useEffect(() => {
    if (!isAuthenticated || autoGeneratedRef.current || extensionConnectCode) {
      return;
    }

    autoGeneratedRef.current = true;
    let cancelled = false;
    setIsBusy(true);

    const request = connectCodeRequestRef.current ?? requestExtensionConnectCode();
    if (!connectCodeRequestRef.current) {
      connectCodeRequestRef.current = request;
    }

    void request
      .then((result) => {
        if (cancelled) {
          return;
        }
        if (!result.ok) {
          setStatusMessage(result.errorMessage);
          return;
        }

        setExtensionConnectCode(result.connectCode);
        setExtensionCodeExpiresAt(result.expiresAt);
      })
      .finally(() => {
        if (connectCodeRequestRef.current === request) {
          connectCodeRequestRef.current = null;
        }
        if (!cancelled) {
          setIsBusy(false);
        }
      });

    return () => {
      cancelled = true;
    };
  }, [extensionConnectCode, isAuthenticated]);

  async function getExtensionConnectCode(options: { forceNew?: boolean } = {}) {
    const expiresAtMs = extensionCodeExpiresAt ? Date.parse(extensionCodeExpiresAt) : Number.POSITIVE_INFINITY;
    const hasFreshExistingCode = Boolean(extensionConnectCode) && expiresAtMs > Date.now();
    if (!options.forceNew && extensionConnectCode && hasFreshExistingCode) {
      return extensionConnectCode;
    }

    const request = connectCodeRequestRef.current ?? requestExtensionConnectCode();
    if (!connectCodeRequestRef.current) {
      connectCodeRequestRef.current = request;
    }

    const result = await request.finally(() => {
      if (connectCodeRequestRef.current === request) {
        connectCodeRequestRef.current = null;
      }
    });

    if (!result.ok) {
      setStatusMessage(result.errorMessage);
      return null;
    }

    setExtensionConnectCode(result.connectCode);
    setExtensionCodeExpiresAt(result.expiresAt);
    return result.connectCode;
  }

  async function generateExtensionConnectCode() {
    setIsBusy(true);
    setStatusMessage(null);
    try {
      const connectCode = await getExtensionConnectCode({ forceNew: true });
      if (!connectCode) {
        return;
      }

      setStatusMessage("New connect code ready.");
    } finally {
      setIsBusy(false);
    }
  }

  async function handleChromeWebStoreClick() {
    if (!isAuthenticated) {
      return;
    }

    setIsBusy(true);
    setStatusMessage(null);
    try {
      const connectCode = await getExtensionConnectCode();
      if (!connectCode) {
        return;
      }

      const copied = await copyText(connectCode);
      setStatusMessage(
        copied ? "Chrome Web Store opened and your connect code was copied." : "Chrome Web Store opened. Your connect code is ready below."
      );
    } finally {
      setIsBusy(false);
    }
  }

  async function revokeExtensionTokens() {
    setIsBusy(true);
    setStatusMessage(null);
    try {
      const response = await fetch("/api/auth/extension/revoke", {
        method: "POST",
      });
      const json = await response.json();
      if (!response.ok) {
        setStatusMessage(json.error_message || "Could not revoke extension tokens.");
        return;
      }

      setStatusMessage(`Revoked ${json.revoked ?? 0} extension token(s). Reconnect extension to continue captures.`);
      setExtensionConnectCode(null);
      setExtensionCodeExpiresAt(null);
    } finally {
      setIsBusy(false);
    }
  }

  return (
    <section className="card scroll-mt-24 p-4 sm:p-5" id={id}>
      <h2 className="text-lg font-semibold">Chrome Extension</h2>
      <p className="mt-1 text-sm text-[var(--muted)]">
        Install ArticlePod Capture from Chrome Web Store. Signed-in users get a one-time connect code prepared automatically on this page;
        it stays valid for 24 hours, and the extension stays connected until you revoke it.
      </p>
      <div className="mt-4 rounded-2xl border border-[rgba(31,122,90,0.18)] bg-[var(--accent-soft)]/45 p-4 sm:p-5">
        <p className="text-xs font-semibold uppercase tracking-[0.16em] text-[var(--accent)]">Setup actions</p>
        <div className="mt-3 grid grid-cols-1 gap-2 sm:flex sm:flex-wrap sm:items-center">
          <a
            className="w-full rounded-lg bg-[var(--accent)] px-3 py-2 text-center text-sm font-semibold text-white sm:w-auto"
            href={CHROME_WEB_STORE_URL}
            onClick={() => {
              void handleChromeWebStoreClick();
            }}
            rel="noopener noreferrer"
            target="_blank"
          >
            Add to Chrome (Chrome Web Store)
          </a>
          {isAuthenticated ? (
            <>
              <button className="w-full rounded-lg border bg-white px-3 py-2 text-sm sm:w-auto" onClick={generateExtensionConnectCode} disabled={isBusy}>
                {extensionConnectCode ? "Generate new code" : "Generate connect code"}
              </button>
              <button className="w-full rounded-lg border bg-white px-3 py-2 text-sm sm:w-auto" onClick={revokeExtensionTokens} disabled={isBusy}>
                Revoke extension tokens
              </button>
            </>
          ) : (
            <Link className="w-full rounded-lg border bg-white px-3 py-2 text-center text-sm sm:w-auto" href={loginHref}>
              Log in to generate connect code
            </Link>
          )}
        </div>
        {isAuthenticated ? (
          extensionConnectCode ? (
            <div className="mt-4">
              <CopyableValueBox
                copiedMessage="Extension connect code copied."
                idleMessage="Tap or click the box to copy your connect code."
                label="One-time connect code"
                tone="accent"
                value={extensionConnectCode}
                valueClassName="text-sm"
              />
              <p className="mt-2 text-xs text-[var(--muted)]">
                Expires: {extensionCodeExpiresAt ? new Date(extensionCodeExpiresAt).toLocaleString() : "soon"}
              </p>
            </div>
          ) : (
            <div className="mt-4 rounded-2xl border border-[rgba(31,122,90,0.34)] bg-[rgba(223,243,236,0.82)] p-4 shadow-[0_0_0_1px_rgba(31,122,90,0.06)]">
              <p className="text-xs font-semibold uppercase tracking-[0.16em] text-[var(--accent)]">One-time connect code</p>
              <div className="mt-2 rounded-xl border border-[rgba(31,122,90,0.18)] bg-white/92 px-4 py-3">
                <p className="text-sm text-[var(--ink)]">
                  {isBusy ? "Preparing your one-time connect code..." : "Generate a one-time connect code when you are ready to pair the extension."}
                </p>
              </div>
            </div>
          )
        ) : (
          <div className="mt-4 rounded-xl border border-dashed border-slate-200 bg-white px-4 py-3">
            <p className="text-sm font-medium text-slate-900">Connect code stays hidden until you log in</p>
            <p className="mt-1 text-sm text-[var(--muted)]">
              Public visitors can see the same setup steps, but only signed-in users can generate or copy the one-time connect code.
            </p>
          </div>
        )}
      </div>
      {statusMessage ? <p className="mt-3 text-sm text-[var(--muted)]">{statusMessage}</p> : null}
    </section>
  );
}
